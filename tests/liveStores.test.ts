// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { nextTick, ref } from "vue";
import type { AnyWebSocketMessage } from "../shared/types/WebSocketMessages";
import { vueGlobals, withSetup } from "./helpers/vue";
const getSocket = vi.hoisted(() => vi.fn());
vi.mock("../app/composables/useSharedAuthWebSocket", () => ({ useSharedAuthWebSocket: getSocket }));
let receive: (message: AnyWebSocketMessage) => void;
const socket = { status: ref("CLOSED"), peerId: ref("self"), sendMessage: vi.fn(), open: vi.fn(), close: vi.fn(), subscribe: vi.fn() };
const status = ref("authenticated"), user = ref<{
    id: number;
    name: string;
} | null>({ id: 1, name: "Me" });
const snackbar = { showPersistent: vi.fn(), hide: vi.fn(), showMessage: vi.fn() };
const isEditing = ref(false), selectedId = ref<number | null>(1);
const wrappers: Array<{
    unmount(): void;
}> = [];
const stores: Array<{
    $dispose(): void;
}> = [];
beforeEach(() => {
    vueGlobals();
    vi.clearAllMocks();
    socket.status.value = "CLOSED";
    isEditing.value = false;
    selectedId.value = 1;
    status.value = "authenticated";
    user.value = { id: 1, name: "Me" };
    socket.subscribe.mockImplementation((fn) => { receive = fn; return vi.fn(); });
    getSocket.mockReturnValue(socket);
    vi.stubGlobal("useAuth", () => ({ status, data: user }));
    vi.stubGlobal("useSnackbar", () => snackbar);
    vi.stubGlobal("storeToRefs", (value: unknown) => value);
    vi.stubGlobal("useSelectedIssue", () => ({ selectedId }));
    vi.stubGlobal("useIsEditing", () => ({ isEditing }));
});
afterEach(() => { stores.splice(0).forEach((store) => store.$dispose()); wrappers.splice(0).forEach((wrapper) => wrapper.unmount()); vi.unstubAllGlobals(); });
function message(type: string, payload: unknown) { receive({ type, payload } as AnyWebSocketMessage); }
describe("presence, connection warnings and editing lock stores", () => {
    it("warns once on disconnect and announces recovery, stopping watchers on unmount", async () => {
        const { useConnectionStatus } = await import("../app/composables/useConnectionStatus");
        const mounted = withSetup(useConnectionStatus);
        wrappers.push(mounted.wrapper);
        socket.status.value = "OPEN";
        await nextTick();
        expect(snackbar.showMessage).not.toHaveBeenCalled();
        socket.status.value = "CLOSED";
        await nextTick();
        socket.status.value = "CONNECTING";
        await nextTick();
        expect(snackbar.showPersistent).toHaveBeenCalledTimes(1);
        socket.status.value = "OPEN";
        await nextTick();
        expect(mounted.value.isConnected.value).toBe(true);
        expect(snackbar.hide).toHaveBeenCalledTimes(1);
        expect(snackbar.showMessage).toHaveBeenCalledWith("Verbinding hersteld");
        mounted.wrapper.unmount();
        socket.status.value = "CLOSED";
        await nextTick();
        expect(snackbar.showPersistent).toHaveBeenCalledTimes(1);
    });
    it("registers authenticated users, deduplicates peers and reports joins/leaves", async () => {
        const { useOnlineUsers } = await import("../app/composables/useOnlineUsers");
        const mounted = withSetup(() => useOnlineUsers());
        wrappers.push(mounted.wrapper);
        stores.push(mounted.value);
        const store = mounted.value;
        expect(socket.open).toHaveBeenCalledTimes(1);
        socket.status.value = "OPEN";
        await nextTick();
        expect(socket.sendMessage).toHaveBeenCalledWith("user-online", {});
        const self = { peerId: "self", username: "me", name: "Me", userId: 1, connectedAt: 1 };
        const other = { peerId: "other", username: "other", name: "Other User", userId: 2, connectedAt: 2 };
        message("online-users", [self]);
        await nextTick();
        message("peer-connected", "self");
        expect(store.displayedUserCount).toBe(0);
        message("online-users", [self, other, { ...other, peerId: "newer", connectedAt: 3 }]);
        await nextTick();
        expect(store.displayedOnlineUsers).toEqual([{ ...other, peerId: "newer", connectedAt: 3 }]);
        expect(snackbar.showMessage).toHaveBeenCalledWith("Other User is ook ingelogd", "info");
        message("online-users", [self, { ...self, peerId: "second" }, other]);
        await nextTick();
        expect(store.displayedUserCount).toBe(2);
        expect(store.onlineUserCount).toBe(3);
        message("online-users", [self]);
        await nextTick();
        expect(snackbar.showMessage).toHaveBeenCalledWith("Other User is uitgelogd", "info");
        expect(store.getUserInitials(other)).toBe("OU");
        expect(store.getUserInitials({ ...other, name: null })).toBe("OT");
        expect(store.getUserInitials({ ...other, name: "", username: "" })).toBe("U");
        expect(store.getUserAvatarColor(other)).toBe("#424242");
        socket.status.value = "CLOSED";
        await nextTick();
        expect(store.onlineUsers).toEqual([]);
        status.value = "unauthenticated";
        await nextTick();
        expect(socket.close).toHaveBeenCalled();
        store.notifyUserOnline();
        store.notifyUserOffline();
    });
    it("sends editing transitions, distinguishes own locks and clears stale locks on reconnect", async () => {
        vi.stubGlobal("useConnectionStatus", () => ({ isConnected: ref(true) }));
        const { useIssueLocks } = await import("../app/composables/useIssueLocks");
        const mounted = withSetup(() => useIssueLocks());
        wrappers.push(mounted.wrapper);
        stores.push(mounted.value);
        const store = mounted.value;
        socket.status.value = "OPEN";
        await nextTick();
        store.acquireLock(1);
        expect(socket.sendMessage).toHaveBeenCalledWith("lockIssue", { issueId: 1 });
        store.releaseLock(1);
        expect(socket.sendMessage).toHaveBeenCalledWith("unlockIssue", { issueId: 1 });
        store.acquireLock(2);
        message("editing-status", { 2: { peer: "other", username: "user", displayName: "Other", lockedAt: Date.now() }, 3: { peer: "self", username: "me", displayName: "Me", lockedAt: Date.now() } });
        expect(store.isLocked(2)).toBe("Other");
        expect(store.isLocked(3)).toBe(false);
        expect(store.isLocked(99)).toBe(false);
        expect(store.locks).toEqual({ 2: "Other" });
        expect(store.getEditAvailability(2)).toEqual({ status: "locked", lockedBy: "Other" });
        expect(store.getEditAvailability(3)).toEqual({ status: "available" });
        expect(store.getEditAvailability(null)).toEqual({ status: "available" });
        socket.status.value = "CLOSED";
        expect(store.getEditAvailability(2)).toEqual({ status: "disconnected" });
        expect(store.getEditAvailability(null)).toEqual({ status: "disconnected" });
        await nextTick();
        expect(store.locks).toEqual({});
        socket.status.value = "OPEN";
        await nextTick();
        expect(socket.sendMessage).toHaveBeenLastCalledWith("lockIssue", { issueId: 2 });
        store.releaseLock(2);
        selectedId.value = null;
        await nextTick();
        socket.status.value = "CLOSED";
        await nextTick();
        socket.status.value = "OPEN";
        await nextTick();
        expect(socket.sendMessage).toHaveBeenLastCalledWith("clearMyLocks", {});
    });
    it("keeps availability and owned locks consistent across reconnect and authentication changes", async () => {
        const { useIssueLocks } = await import("../app/composables/useIssueLocks");
        const mounted = withSetup(() => useIssueLocks());
        wrappers.push(mounted.wrapper);
        const store = mounted.value;
        stores.push(store);
        store.acquireLock(9);
        expect(socket.sendMessage).not.toHaveBeenCalledWith("lockIssue", { issueId: 9 });
        store.releaseLock(9);
        store.releaseLock(9);
        socket.status.value = "OPEN";
        await nextTick();
        store.acquireLock(9);
        message("editing-status", {
            4: { peer: "other", username: "fallback", displayName: "", lockedAt: 1 },
        });
        expect(store.getEditAvailability(4)).toEqual({ status: "locked", lockedBy: "fallback" });
        status.value = "unauthenticated";
        await nextTick();
        expect(socket.sendMessage).toHaveBeenLastCalledWith("clearMyLocks", {});
        status.value = "authenticated";
        await nextTick();
        expect(socket.sendMessage).toHaveBeenLastCalledWith("lockIssue", { issueId: 9 });
        store.releaseLock(9);
        store.cleanup();
    });
    it("acquires and releases edit-form locks as the issue changes and the form unmounts", async () => {
        vi.stubGlobal("useConnectionStatus", () => ({ isConnected: ref(true) }));
        socket.status.value = "OPEN";
        const { useIssueEditLock } = await import("../app/composables/useIssueEditLock");
        const issueId = ref<number | null>(1);
        const mounted = withSetup(() => {
            useIssueEditLock(issueId);
            return null;
        });
        wrappers.push(mounted.wrapper);
        const secondEditor = withSetup(() => {
            useIssueEditLock(1);
            return null;
        });
        wrappers.push(secondEditor.wrapper);
        const store = (await import("../app/composables/useIssueLocks")).useIssueLocks();
        stores.push(store);
        expect(socket.sendMessage).toHaveBeenCalledWith("lockIssue", { issueId: 1 });
        issueId.value = 2;
        await nextTick();
        expect(socket.sendMessage).not.toHaveBeenCalledWith("unlockIssue", { issueId: 1 });
        secondEditor.wrapper.unmount();
        wrappers.splice(wrappers.indexOf(secondEditor.wrapper), 1);
        expect(socket.sendMessage).toHaveBeenCalledWith("unlockIssue", { issueId: 1 });
        expect(socket.sendMessage).toHaveBeenCalledWith("lockIssue", { issueId: 2 });
        mounted.wrapper.unmount();
        expect(socket.sendMessage).toHaveBeenLastCalledWith("unlockIssue", { issueId: 2 });
    });
});
