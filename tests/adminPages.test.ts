// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { mount, flushPromises } from "@vue/test-utils";
import { defineComponent, h, ref, shallowRef } from "vue";
import { vueGlobals } from "./helpers/vue";
import { Field, Slot, uiStubs } from "./helpers/ui";
import Tags from "../app/pages/admin/tags/index.vue";
import Categories from "../app/pages/admin/legends/index.vue";
import Users from "../app/pages/admin/users/index.vue";
import Texts from "../app/pages/admin/texts/index.vue";
const Table = defineComponent({ props: ["items"], setup(props, { slots }) { return () => h("div", (props.items ?? []).map((item: unknown) => h("section", Object.entries(slots).filter(([name]) => name.startsWith("item.")).map(([, slot]) => slot?.({ item }))))); } });
const Child = defineComponent({ name: "BoundaryChild", props: ["modelValue", "entry", "legend", "legends", "error", "usage", "user", "loading"], emits: ["save", "saved", "submit", "cancel", "confirm", "edit", "delete"], template: "<div>{{ legends?.length }}</div>" });
const TagEditorStub = defineComponent({ name: "TagEditor", props: ["open", "modelValue"], emits: ["update:open", "saved", "deleted"], template: "<div></div>", setup() { return { openCreateDialog: vi.fn(), openEditDialog: vi.fn() }; }, expose: ["openCreateDialog", "openEditDialog"] });
const stubs = { ...uiStubs, VDataTable: Table, VTable: Slot, VTextarea: Field, VChip: Slot, IconSelector: Field, AppIcon: true, UserForm: Child, AdminLegendTable: Child, AdminLegendDialog: Child, AdminLegendDeleteConfirmDialog: Child, TextEditorDialog: Child, TagEditor: TagEditorStub };
const create = vi.fn(), update = vi.fn(), remove = vi.fn(), showError = vi.fn(), showSuccess = vi.fn();
const rows = ref<Record<string, unknown>[]>([]), categories = shallowRef<Record<string, unknown>[]>([]), users = ref<Record<string, unknown>[]>([]);
const wrappers: Array<{
    unmount(): void;
}> = [];
beforeEach(() => {
    vueGlobals();
    vi.clearAllMocks();
    create.mockReset();
    update.mockReset();
    remove.mockReset();
    rows.value = [];
    categories.value = [];
    users.value = [];
    vi.stubGlobal("useTitle", vi.fn());
    vi.stubGlobal("definePageMeta", vi.fn());
    vi.stubGlobal("useRoles", () => ({ isAdmin: ref(true) }));
    vi.stubGlobal("requiredRule", (x: string) => !!x);
    vi.stubGlobal("storeToRefs", (x: unknown) => x);
    vi.stubGlobal("useTagsApi", () => ({ tags: rows, create, update, remove, refreshTags: vi.fn() }));
    vi.stubGlobal("useCategories", () => ({ categories, create, update, remove, getUsage: async () => ({}) }));
    vi.stubGlobal("useUsersApi", () => ({ users, create, update, remove }));
    vi.stubGlobal("useRuntimeConfig", () => ({ public: { appUrl: "https://example.test" } }));
    vi.stubGlobal("useSnackbar", () => ({ showError, showSuccess }));
    vi.spyOn(console, "error").mockImplementation(() => { });
});
afterEach(() => { wrappers.splice(0).forEach((w) => w.unmount()); vi.unstubAllGlobals(); vi.restoreAllMocks(); });
const button = (wrapper: ReturnType<typeof mount>, text: string) => wrapper.findAll("button").find((b) => b.text().trim() === text)!;
it("renders tags page with table and editor", async () => {
    const wrapper = mount(Tags, { global: { stubs, mocks: { requiredRule: () => true } } });
    wrappers.push(wrapper);
    expect(wrapper.text()).toContain("Tags");
    expect(wrapper.text()).toContain("Nieuwe tag");
    // TagEditor is stubbed, so we just verify the page renders
    expect(wrapper.findComponent(TagEditorStub).exists()).toBe(true);
});
it("creates/edits categories and displays protected-delete errors without dropping the item", async () => {
    categories.value = [{ id: 1, name: "Routes" }];
    const wrapper = mount(Categories, { global: { stubs } });
    wrappers.push(wrapper);
    await flushPromises();
    const table = wrapper.findAllComponents(Child)[0]!;
    const dialog = wrapper.findAllComponents(Child)[1]!;
    const deletion = wrapper.findAllComponents(Child)[2]!;
    create.mockResolvedValueOnce({ id: 2, name: "New" });
    dialog.vm.$emit("save", { name: "New", color: "#fff", description: "" });
    await flushPromises();
    expect(categories.value).toHaveLength(2);
    expect(table.text()).toBe("2");
    table.vm.$emit("edit", categories.value[0]);
    await flushPromises();
    dialog.vm.$emit("save", { name: "Changed", color: "#fff", description: "" });
    await flushPromises();
    expect(update).toHaveBeenCalledWith(1, expect.objectContaining({ name: "Changed" }));
    table.vm.$emit("delete", categories.value[0]);
    await flushPromises();
    remove.mockRejectedValueOnce({ data: { message: "In use" } });
    deletion.vm.$emit("confirm");
    await flushPromises();
    expect(deletion.props("error")).toBe("In use");
    expect(categories.value).toHaveLength(2);
    remove.mockResolvedValueOnce({ success: true });
    deletion.vm.$emit("confirm");
    await flushPromises();
    expect(categories.value).toEqual([{ id: 2, name: "New" }]);
});
it("creates, edits and deletes users and copies their reset links", async () => {
    users.value = [{ id: 1, username: "user@example.test", name: "User", role: "user", reset_token: "token", reset_token_expires_at: "2099-01-01T00:00:00Z" }];
    const clipboard = { writeText: vi.fn().mockResolvedValue(undefined) };
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: clipboard });
    const wrapper = mount(Users, { global: { stubs } });
    wrappers.push(wrapper);
    await button(wrapper, "Nieuwe gebruiker").trigger("click");
    const newForm = wrapper.findAllComponents(Child).find((c) => c.props("user") === undefined)!;
    newForm.vm.$emit("submit", { username: "new", name: null, role: "user" });
    await flushPromises();
    expect(create).not.toHaveBeenCalled();
    newForm.vm.$emit("submit", { username: "new", name: null, role: "user", password: "pw" });
    await flushPromises();
    expect(create).toHaveBeenCalledWith(expect.objectContaining({ username: "new", password: "pw" }));
    await wrapper.get('button[icon="mdi-pencil"]').trigger("click");
    const edit = wrapper.findAllComponents(Child).find((c) => c.props("user")?.id === 1)!;
    edit.vm.$emit("submit", { username: "updated", name: "User", role: "admin" });
    await flushPromises();
    expect(update).toHaveBeenCalledWith(1, expect.objectContaining({ username: "updated" }));
    const copy = wrapper.findAll("button").find((b) => b.text().includes("Kopieer reset link"))!;
    await copy.trigger("click");
    await flushPromises();
    expect(clipboard.writeText).toHaveBeenCalledWith("https://example.test/reset-password/token");
    await wrapper.get('button[icon="mdi-delete"]').trigger("click");
    await button(wrapper, "Verwijderen").trigger("click");
    await flushPromises();
    expect(remove).toHaveBeenCalledWith(1);
});
