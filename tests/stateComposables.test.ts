// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { computed, effectScope, nextTick, reactive, ref } from "vue";
import { vueGlobals } from "./helpers/vue";
const auth = { token: ref("Bearer token"), status: ref("authenticated"), data: ref<{
        id: number;
        role: string;
    } | null>({ id: 1, role: "admin" }) };
let scope: ReturnType<typeof effectScope>;
beforeEach(() => { vueGlobals(); scope = effectScope(); vi.stubGlobal("useAuth", () => auth); auth.status.value = "authenticated"; auth.data.value = { id: 1, role: "admin" }; });
afterEach(() => { scope.stop(); vi.unstubAllGlobals(); });
it("resets editing when authentication changes", async () => {
    const { useIsEditing } = await import("../app/composables/useIsEditing");
    const state = scope.run(useIsEditing)!;
    state.setEditing(true);
    expect(state.isEditing.value).toBe(true);
    state.toggleEditing();
    expect(state.isEditing.value).toBe(false);
    state.setEditing(true);
    auth.status.value = "unauthenticated";
    await nextTick();
    expect(state.isEditing.value).toBe(false);
});
it("derives current roles reactively without allowing callers to modify the role list", async () => {
    const { useRoles } = await import("../app/composables/useRoles");
    const roles = useRoles();
    expect(roles.isAdmin.value).toBe(true);
    expect(roles.hasRole("admin")).toBe(true);
    expect(roles.getRoleInfo("user")).toMatchObject({ name: "user" });
    roles.getAllRoles().pop();
    expect(roles.getAllRoles()).toHaveLength(2);
    auth.data.value = { id: 2, role: "user" };
    expect(roles.isAdmin.value).toBe(false);
    expect(roles.hasRole("admin")).toBe(false);
    auth.data.value = null;
    expect(roles.currentRole.value).toBeNull();
});
it("shows transient, persistent, success and error snackbar messages and hides the shared instance", async () => {
    const { useSnackbar } = await import("../app/composables/useSnackbar");
    const a = useSnackbar(), b = useSnackbar();
    a.showMessage("Saved");
    expect(b.snackbar.value).toEqual({ show: true, text: "Saved", color: "success", timeout: 4000 });
    a.showPersistent("Offline");
    expect(b.snackbar.value.timeout).toBe(-1);
    a.hide();
    expect(b.snackbar.value.show).toBe(false);
    a.showSuccess("OK");
    expect(b.snackbar.value.color).toBe("success");
    a.showError("Failed");
    expect(b.snackbar.value.color).toBe("error");
});
it("syncs tag selections with navigation and preserves unrelated query parameters", async () => {
    const route = reactive({ path: "/kaart", query: { tag: "bike,bike+safe", cat: "1" } as Record<string, unknown> });
    const replace = vi.fn(async ({ query }: {
        query: Record<string, unknown>;
    }) => { route.query = query; });
    vi.stubGlobal("useRoute", () => route);
    vi.stubGlobal("useRouter", () => ({ replace }));
    const { useTagFilters } = await import("../app/composables/useTagFilter");
    const tags = scope.run(() => useTagFilters())!;
    expect(tags.selectedTags).toEqual(["bike", "safe"]);
    await tags.toggleTag("safe");
    expect(tags.hasTag("safe")).toBe(false);
    await tags.toggleTag("new");
    expect(route.query.tag).toBe("bike+new");
    await tags.setTag("only");
    expect(route.query).toEqual({ tag: "only", cat: "1" });
    await tags.clearTags();
    expect(route.query).toEqual({ cat: "1" });
    route.query.tag = ["invalid"];
    await nextTick();
    expect(tags.selectedTags).toEqual([]);
    tags.$dispose();
});
it("filters by categories in use, toggles show-all state and keeps other query parameters", async () => {
    const route = reactive({ query: { tag: "bike" } as Record<string, unknown> });
    const categories = ref([{ id: 1 }, { id: 2 }, { id: 3 }]);
    const issues = ref([{ legend_id: 1 }, { legend_id: 2 }, { legend_id: null }]);
    vi.stubGlobal("storeToRefs", (value: unknown) => value);
    vi.stubGlobal("useCategories", () => ({ categories }));
    vi.stubGlobal("useIssues", () => ({ issues }));
    vi.stubGlobal("useRoute", () => route);
    vi.stubGlobal("useRouter", () => ({ replace: async ({ query }: {
            query: Record<string, unknown>;
        }) => { route.query = query; } }));
    const { useCategoryFilters } = await import("../app/composables/useCategoryFilters");
    const filters = scope.run(() => useCategoryFilters())!;
    expect(filters.usedCategories).toEqual([{ id: 1 }, { id: 2 }]);
    expect(filters.isShowingAllCategories).toBe(true);
    await filters.toggleCategoryVisibility(1);
    expect(route.query).toEqual({ cat: "1", tag: "bike" });
    expect(filters.isCategoryVisible(2)).toBe(false);
    await filters.toggleCategoryVisibility(1);
    expect(filters.isShowingAllCategories).toBe(true);
    route.query.cat = "1,999,not-a-number";
    expect([...filters.visibleCategoryIds]).toEqual([1]);
    await filters.toggleCategoryVisibility(2);
    expect(route.query.cat).toBeUndefined();
    await filters.showAllCategories();
    expect(filters.isCategoryVisible(1)).toBe(true);
    filters.$dispose();
});
it("combines tag AND selection with visible categories and handles empty data", async () => {
    const all = ref([{ id: 1, legend_id: 1, tags: ["bike", "safe"] }, { id: 2, legend_id: 2, tags: ["bike"] }]);
    const tags = ref<string[]>([]), categories = ref(new Set([1, 2])), showingAll = ref(true);
    vi.stubGlobal("storeToRefs", (value: unknown) => value);
    vi.stubGlobal("useIssues", () => ({ issues: all }));
    vi.stubGlobal("useTagFilters", () => ({ selectedTags: tags }));
    vi.stubGlobal("useCategoryFilters", () => ({ visibleCategoryIds: categories, isShowingAllCategories: showingAll }));
    const { useSelectedIssues } = await import("../app/composables/useSelectedIssues");
    const { selectedIssues } = useSelectedIssues();
    expect(selectedIssues.value).toHaveLength(2);
    tags.value = ["bike", "safe"];
    expect(selectedIssues.value.map((x) => x.id)).toEqual([1]);
    showingAll.value = false;
    categories.value = new Set([2]);
    expect(selectedIssues.value).toEqual([]);
    tags.value = [];
    expect(selectedIssues.value.map((x) => x.id)).toEqual([2]);
    all.value = [];
    expect(selectedIssues.value).toEqual([]);
});
it("sets the page title and preserves the last nonempty title", async () => {
    const head = vi.fn();
    vi.stubGlobal("useHead", head);
    vi.stubGlobal("useRuntimeConfig", () => ({ public: { organization: { name: "Test Organization" } } }));
    const { useTitle } = await import("../app/composables/useTitle");
    const title = ref("Map");
    const result = scope.run(() => useTitle(title))!;
    expect(head).toHaveBeenCalledWith({ title, titleTemplate: "%s - Test Organization" });
    title.value = "Issue";
    await nextTick();
    expect(result.currentTitle.value).toBe("Issue");
    title.value = "";
    await nextTick();
    expect(result.currentTitle.value).toBe("Issue");
    expect(computed(() => result.currentTitle.value).value).toBe("Issue");
});
