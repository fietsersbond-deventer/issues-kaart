it("keeps Street View passive until a deliberate click, enhances once and replaces the preview once", () => {
    const container = document.createElement("div");
    container.innerHTML = '<div class="streetview-embed" data-embed-src="https://www.google.com/maps/embed?pb=test"><img src="data:image/png;base64,YQ=="></div><p>Unrelated</p>';
    document.body.append(container);
    const embeds = useStreetViewEmbeds();
    expect(container.querySelector("iframe")).toBeNull();
    const target = container.querySelector("img")!;
    target.addEventListener("click", embeds.handleClick);
    target.dispatchEvent(new MouseEvent("click"));
    expect(container.querySelector("iframe")).toBeNull();
    embeds.activate(container);
    embeds.activate(container);
    expect(container.querySelectorAll("button")).toHaveLength(1);
    const button = container.querySelector("button")!;
    button.addEventListener("click", embeds.handleClick);
    button.click();
    const iframe = container.querySelector("iframe")!;
    expect(iframe.src).toContain("google.com/maps/embed");
    expect(iframe.title).toBe("Street View");
    expect(container.querySelector("img")).toBeNull();
    iframe.addEventListener("click", embeds.handleClick);
    iframe.dispatchEvent(new MouseEvent("click"));
    expect(container.querySelectorAll("iframe")).toHaveLength(1);
    embeds.handleClick(new MouseEvent("click"));
});
it("normalizes icon metadata, searches aliases/tags and recovers when metadata is unavailable", async () => {
    const fetch = vi.fn().mockResolvedValueOnce({ json: async () => [{ name: "bike", tags: ["transport", "outdoors"], category: "bicycle", aliases: ["cycle"] }, { name: "tree" }] });
    vi.stubGlobal("fetch", fetch);
    const icons = await getAllMdiIcons();
    expect(icons[1]).toEqual({ name: "mdi-tree", tags: [], category: "uncategorized", aliases: [] });
    expect(getIconsByTag(icons, "TRANSPORT")).toHaveLength(1);
    expect(getTransportIcons(icons)).toHaveLength(1);
    expect(searchIcons(icons, "cycle")).toHaveLength(1);
    expect(searchIcons(icons, "outdoors")).toHaveLength(1);
    expect(searchIcons(icons, "tree")).toHaveLength(1);
    expect(getTagOptions([...icons, icons[0]!])[0]).toEqual({ title: "transport (2)", value: "transport" });
    fetch.mockRejectedValueOnce(new Error("offline"));
    expect(await getAllMdiIcons()).toEqual([]);
});
it("checks icon CSS and always cleans up its temporary element, including failed style reads", () => {
    const style = vi.spyOn(window, "getComputedStyle");
    for (const [content, available] of [['"\\f123"', true], ["none", false], ['""', false], ["", false]]) {
        style.mockReturnValue({ getPropertyValue: () => content } as CSSStyleDeclaration);
        expect(isMdiIconAvailable("mdi-bike")).toBe(available);
        expect(document.body.children).toHaveLength(0);
    }
    style.mockImplementation(() => { throw new Error("unavailable"); });
    expect(filterAvailableIcons(["bike"])).toEqual([]);
    expect(document.body.children).toHaveLength(0);
});
it("builds bounded case-insensitive search snippets without matching empty terms", () => {
    expect(getMatch("one two BIKE three four five six", "bike", 1)).toBe("... BIKE ...");
    expect(getMatches("bike here far apart bike", "bike", 0)).toEqual(["...bike...", "...bike..."]);
    expect(getMatches("text", "")).toEqual([]);
    expect(getMatch("text", "missing")).toBeUndefined();
    expect(requiredRule("")).toBe("Verplicht veld");
    expect(requiredRule("value")).toBe(true);
    expect(getPlainText("<p>One</p><script>bad()</script><p>Two</p>")).toBe("One Two");
    expect(getPlainText("")).toBe("");
});
it("classifies new/existing issues and supported message families", () => {
    expect(isExistingIssue(null)).toBe(false);
    expect(isExistingIssue({ id: 1 })).toBe(true);
    expect(isNewIssue({ title: "Draft", description: "", tags: [] })).toBe(true);
    const message = createWebSocketMessage("lockIssue", { issueId: 1 });
    expect(isLockMessage(message)).toBe(true);
    expect(isMessageOfType(message, "lockIssue")).toBe(true);
    expect(isOnlineUserMessage(createWebSocketMessage("user-online", {}))).toBe(true);
    expect(isIssueMessage({ type: "issue-created" })).toBe(true);
    for (const invalid of [null, undefined, "x", {}, { type: "unknown" }]) {
        expect(isLockMessage(invalid)).toBe(false);
        expect(isOnlineUserMessage(invalid)).toBe(false);
        expect(isIssueMessage(invalid)).toBe(false);
    }
});
it("clamps bottom-sheet drag height, snaps near targets and scrolls when selection changes", async () => {
    const selectedId = ref(1);
    vi.stubGlobal("storeToRefs", (x: unknown) => x);
    vi.stubGlobal("useSelectedIssue", () => ({ selectedId }));
    vi.stubGlobal("useVDisplay", () => ({ mobile: ref(true) }));
    const { useBottomSheet } = await import("../app/composables/useBottomSheet");
    const sheet = scope.run(() => useBottomSheet())!;
    sheet.setHeight(100);
    expect(sheet.sheetHeight.value).toBe(75);
    sheet.setHeight(-1);
    expect(sheet.sheetHeight.value).toBe(10);
    sheet.setHeight(34);
    sheet.endDrag();
    expect(sheet.sheetHeight.value).toBe(30);
    sheet.setHeight(50);
    sheet.endDrag();
    expect(sheet.sheetHeight.value).toBe(50);
    sheet.reset();
    expect(sheet.sheetHeight.value).toBe(30);
    sheet.startDragMouse(new MouseEvent("mousedown", { clientY: 100 }));
    document.dispatchEvent(new MouseEvent("mousemove", { clientY: 0 }));
    expect(sheet.sheetHeight.value).toBeGreaterThan(30);
    document.dispatchEvent(new MouseEvent("mouseup"));
    const height = sheet.sheetHeight.value;
    document.dispatchEvent(new MouseEvent("mousemove", { clientY: 700 }));
    expect(sheet.sheetHeight.value).toBe(height);
    const element = document.createElement("div");
    element.scrollTo = vi.fn();
    sheet.sheetContentRef.value = element;
    selectedId.value = 2;
    await nextTick();
    await nextTick();
    expect(element.scrollTo).toHaveBeenCalledWith({ top: 0, behavior: "smooth" });
    const touch = (clientY: number) => ({ cancelable: true, preventDefault: vi.fn(), touches: [{ clientY }] }) as unknown as TouchEvent;
    sheet.startDrag(touch(100));
    sheet.onDrag(touch(0));
    sheet.endDrag();
    expect(sheet.sheetHeight.value).toBeGreaterThanOrEqual(30);
});
